// This script generates the Supabase client file based on configuration
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Get the directory name in ESM
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Paths
const configTemplatePath = path.resolve(__dirname, '../config.template.json');
const configPath = path.resolve(__dirname, '../config.json');
const clientOutputPath = path.resolve(__dirname, '../integrations/supabase/client.ts');

// Template values
const TEMPLATE_URL = 'YOUR_SUPABASE_URL';
const TEMPLATE_KEY = 'YOUR_SUPABASE_ANON_KEY';

/**
 * Generate the Supabase client file
 */
function generateSupabaseClient() {
  console.log('Generating Supabase client...');
  
  // Try to load the real config
  let supabaseUrl = TEMPLATE_URL;
  let supabaseKey = TEMPLATE_KEY;
  let isUsingTemplateCredentials = true;
  
  try {
    if (fs.existsSync(configPath)) {
      const configContent = fs.readFileSync(configPath, 'utf8');
      const config = JSON.parse(configContent);
      
      if (config.supabase && config.supabase.url && config.supabase.anonKey) {
        supabaseUrl = config.supabase.url;
        supabaseKey = config.supabase.anonKey;
        isUsingTemplateCredentials = false;
        console.log('Using credentials from config.json');
      } else {
        console.warn('config.json exists but does not contain valid Supabase credentials');
      }
    } else {
      console.warn('config.json not found, falling back to template values');
      
      // Try to load template config
      if (fs.existsSync(configTemplatePath)) {
        const templateContent = fs.readFileSync(configTemplatePath, 'utf8');
        const templateConfig = JSON.parse(templateContent);
        
        if (templateConfig.supabase && templateConfig.supabase.url && templateConfig.supabase.anonKey) {
          supabaseUrl = templateConfig.supabase.url;
          supabaseKey = templateConfig.supabase.anonKey;
          console.log('Using credentials from config.template.json');
        }
      } else {
        console.warn('config.template.json not found, using hardcoded template values');
      }
    }
  } catch (error) {
    console.error('Error loading configuration:', error);
    console.warn('Using hardcoded template values');
  }
  
  // Generate the client file content
  const clientContent = `// This file is automatically generated. Do not edit it directly.
import { createClient } from '@supabase/supabase-js';
import type { Database } from './types';

const SUPABASE_URL = "${supabaseUrl}";
const SUPABASE_PUBLISHABLE_KEY = "${supabaseKey}";

// Flag to indicate if we're using template credentials
export const isUsingTemplateCredentials = ${isUsingTemplateCredentials};

// Production check
const isProduction = typeof import.meta !== 'undefined' && 
  typeof import.meta.env !== 'undefined' && 
  import.meta.env.MODE === 'production';

// Show warning or throw error if using template credentials
if (isUsingTemplateCredentials) {
  if (isProduction) {
    throw new Error('Cannot use template Supabase credentials in production. Please configure real credentials in config.json.');
  } else {
    console.warn('Using template Supabase credentials. Replace with real credentials in config.json for full functionality.');
  }
}

// Import the supabase client like this:
// import { supabase, isUsingTemplateCredentials } from "@/integrations/supabase/client";

export const supabase = createClient<Database>(SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY);
`;

  // Write the client file
  fs.writeFileSync(clientOutputPath, clientContent);
  console.log(`Supabase client generated at ${clientOutputPath}`);
}

// Run the generator
generateSupabaseClient();